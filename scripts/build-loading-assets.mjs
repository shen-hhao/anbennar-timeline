// Lossless transport derivatives only. Never writes the historical input JSON.
import {readFile, writeFile, mkdir, readdir} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const dist=new URL('../dist/',import.meta.url),data=new URL('data/',dist);
const generated=new URL('runtime/',data);
await mkdir(generated,{recursive:true});
const read=async name=>JSON.parse(await readFile(new URL(name,data),'utf8'));
const assets={},inputs={};
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
async function pack(name,value,{plain=name}={}){
  const bytes=Buffer.from(JSON.stringify(value)),compressed=gzipSync(bytes,{level:9});
  const hash=sha(compressed),file=`runtime/${name.replace(/\.json$/,'')}.${hash.slice(0,16)}.json.gz`;
  await writeFile(new URL(file,data),compressed);
  return {file,plain,bytes:compressed.length,decodedBytes:bytes.length,sha256:hash};
}
for(const name of (await readdir(data)).filter(name=>name.endsWith('.json')).sort()){
  const bytes=await readFile(new URL(name,data));inputs[name]=sha(bytes);
  assets[name]=await pack(name,JSON.parse(bytes));
}

// The map never renders the 163,000 notices belonging to other research pages.
// Retain every public record/date/country row and all notices it can actually use.
const copy=await read('public-copy.json');
const mapCopy={...copy,continuityRecordsById:{},noticesByKey:Object.fromEntries(
  Object.entries(copy.noticesByKey).filter(([key])=>
    key.startsWith('western-chronology.json:/modelReviewNotes/') ||
    key.startsWith('haless-quality-endpoint-label:/') || key.startsWith('relation-type-label:/')))};
// Re-index only referenced pooled values; unused notices must not drag their
// entire text/source pools back into the first screen. Numeric date fields are
// not pooled values and are deliberately left untouched.
const textPool=[],sourceIdLists=[],textIds=new Map(),sourceIds=new Map();
function remap(index,from,to,ids){
  if(!Number.isInteger(index))return index;
  if(!ids.has(index)){ids.set(index,to.length);to.push(from[index]);}
  return ids.get(index);
}
function row(source){
  const value={...source};
  for(const key of ['title','description','summary','scopeLabel','originalText'])
    if(key in value)value[key]=remap(value[key],copy.textPool,textPool,textIds);
  if(value.questions)value.questions=value.questions.map(v=>remap(v,copy.textPool,textPool,textIds));
  if(Number.isInteger(value.sourceIds))value.sourceIds=remap(value.sourceIds,copy.sourceIdLists,sourceIdLists,sourceIds);
  return value;
}
for(const key of ['eventsById','recordsById','stepsById','historyById','countriesByTag','assessmentsByKey'])
  mapCopy[key]=Object.fromEntries(Object.entries(mapCopy[key]).map(([id,value])=>[id,row(value)]));
mapCopy.noticesByKey=Object.fromEntries(Object.entries(mapCopy.noticesByKey).map(([key,value])=>[key,row(Number.isInteger(value)?copy.noticeRows[value]:value)]));
mapCopy.textPool=textPool;mapCopy.sourceIdLists=sourceIdLists;mapCopy.noticeRows=[];
await writeFile(new URL('map-copy.json',generated),JSON.stringify(mapCopy));
assets['map-copy.json']=await pack('map-copy.json',mapCopy,{plain:'runtime/map-copy.json'});

// The search directory is small. Full original records are requested only for
// the country opened by the reader, including its original source metadata.
const catalog=await read('country-histories.json');
const countries=[];
for(const country of catalog.countries){
  const name=`country-${sha(country.tag).slice(0,16)}.json`;
  const plain=`runtime/${name}`;
  await writeFile(new URL(plain,data),JSON.stringify(country));
  const asset=await pack(name,country,{plain});
  const keys=['tag','name','nameZh','flag','flagNote','aliases','imperialAtStart','reviewLevel','localPoliticalGroup'];
  countries.push({...Object.fromEntries(keys.filter(k=>k in country).map(k=>[k,country[k]])),recordCount:country.records?.length||0,asset});
}
const index={schemaVersion:catalog.schemaVersion,policy:catalog.policy,sources:catalog.sources,countries};
await writeFile(new URL('dossier-index.json',generated),JSON.stringify(index));
assets['dossier-index.json']=await pack('dossier-index.json',index,{plain:'runtime/dossier-index.json'});
const version=sha(JSON.stringify(assets)).slice(0,16);
await writeFile(new URL('loading-assets.js',dist),`// Generated by scripts/build-loading-assets.mjs; original data stays unchanged.\nexport const assetVersion=${JSON.stringify(version)};\nexport const assets=${JSON.stringify(assets,null,2)};\n`);
await writeFile(new URL('loading-assets.json',generated),JSON.stringify({version,inputs,assets,countryFiles:countries.length},null,2)+'\n');
const initial=['atlas.json','names-zh.json','subjects.json','events.json','history.json','western-chronology.json','eras.json','relation-semantics.json','endpoint-review.json','bookmarks.json','map-copy.json','dossier-index.json'];
console.log(JSON.stringify({version,originalInputs:Object.keys(inputs).length,countryFiles:countries.length,initialJsonBytes:initial.reduce((n,k)=>n+assets[k].bytes,0),largestCountryBytes:Math.max(...countries.map(c=>c.asset.bytes)),output:fileURLToPath(generated)},null,2));
